/**
 * Regenerates src/abuse/disposable-domains.ts from the community blocklist at
 * github.com/disposable-email-domains/disposable-email-domains, which is
 * dedicated to the public domain (CC0 1.0), so it can be bundled as is.
 *
 *   bun run scripts/disposable-domains.ts            # fetch the latest list
 *   bun run scripts/disposable-domains.ts list.conf  # or read a local copy
 *
 * Commit the result. Apps add or allow domains at runtime with
 * `isDisposableEmail(email, { add, allow })`; no regeneration needed for that.
 */
import { readFile, writeFile } from "node:fs/promises"

const SOURCE =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf"

const file = process.argv[2]
const text = file ? await readFile(file, "utf8") : await (await fetch(SOURCE)).text()
const domains = [
  ...new Set(
    text
      .split("\n")
      .map((l) => l.trim().toLowerCase())
      .filter((l) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l)),
  ),
].sort()
if (domains.length < 1000) throw new Error(`Only ${domains.length} domains; refusing to write.`)

const out = `// Generated by scripts/disposable-domains.ts. Do not edit by hand.
// Source: github.com/disposable-email-domains/disposable-email-domains (CC0 1.0).
// ${domains.length} domains, updated ${new Date().toISOString().slice(0, 10)}.

/** Newline-separated disposable email domains, lowercase. */
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join("\n"))}
`
await writeFile(new URL("../src/abuse/disposable-domains.ts", import.meta.url), out)
console.log(`wrote ${domains.length} domains`)
