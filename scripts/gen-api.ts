#!/usr/bin/env bun
/**
 * Generate API.md — the single file an agent reads instead of crawling the repo.
 *
 * Built from each package.json's `exports` plus the exported symbols and the
 * first doc line of each source file, so it cannot drift from reality.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "")

/** Exported symbol names, and the first sentence of the file's doc comment. */
function describe(file: string, depth = 0): { symbols: string[]; summary: string } {
  let src = ""
  try {
    src = readFileSync(file, "utf8")
  } catch {
    return { symbols: [], summary: "" }
  }

  // A barrel is `export * from "./x"` and declares nothing itself. Follow it,
  // or the index shows the most useful entry points as empty.
  // Relative imports carry .js extensions (required for Node ESM), so the
  // follower has to strip them or every barrel reads as empty.
  const reexports = [...src.matchAll(/^export\s+\*\s+from\s+"\.\/([\w-]+)(?:\.js)?"/gm)].map(
    (m) => m[1],
  )
  if (reexports.length && depth < 2) {
    const dir = file.slice(0, file.lastIndexOf("/"))
    const merged = reexports.flatMap((r) => describe(`${dir}/${r}.ts`, depth + 1).symbols)
    return {
      symbols: [...new Set(merged)],
      summary: `re-exports ${reexports.join(", ")}`,
    }
  }
  const symbols = [
    ...src.matchAll(/^export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)/gm),
    ...src.matchAll(/^export\s+type\s+(\w+)/gm),
  ].map((m) => m[1])

  const doc = src.match(/^\/\*\*\s*\n([\s\S]*?)\*\//)
  const summary = doc
    ? (
        doc[1]
          .split("\n")
          .map((l) => l.replace(/^\s*\*\s?/, "").trim())
          .filter(Boolean)
          .join(" ")
          .split(/\.\s/)[0] ?? ""
      ).slice(0, 150)
    : ""
  return { symbols, summary }
}

const lines: string[] = [
  "# Signet API index",
  "",
  "Generated by `bun run scripts/gen-api.ts`. **Read this instead of crawling the repo.**",
  "",
  "Every import path below is exact and copy-pasteable.",
  "",
]

for (const pkgDir of readdirSync(join(ROOT, "packages")).sort()) {
  // Export targets are either a path string or a conditions object
  // ({ types, import }) — the latter since exports started pointing at dist.
  type ExportTarget = string | { types?: string; import?: string; default?: string }
  let pkg: { name?: string; exports?: Record<string, ExportTarget>; description?: string }
  try {
    pkg = JSON.parse(readFileSync(join(ROOT, "packages", pkgDir, "package.json"), "utf8"))
  } catch {
    continue
  }
  if (!pkg.exports) continue

  lines.push(`## ${pkg.name}`, "")
  if (pkg.description) lines.push(`${pkg.description}`, "")

  const entries = Object.entries(pkg.exports).sort(([a], [b]) => a.localeCompare(b))
  const isUi = pkg.name === "@dapplelight/signet-ui"

  // The 29 UI components are uniform; a table of them is noise. List the paths.
  /** The source path to read, whichever shape the target is. */
  const targetPath = (t: ExportTarget): string =>
    typeof t === "string" ? t : (t.import ?? t.types ?? t.default ?? "")

  if (isUi) {
    const comps = entries
      .filter(([sub]) => sub.startsWith("./components/"))
      .map(([sub]) => sub.replace("./components/", ""))
    lines.push(
      `\`import { X } from "${pkg.name}/components/<name>"\` — ${comps.length} components:`,
      "",
      comps.map((c) => `\`${c}\``).join(" · "),
      "",
      'Barrel import also works: `import { Button, Card } from "@dapplelight/signet-ui"`.',
      "",
    )
  }

  lines.push("| Import | Exports | What |", "|---|---|---|")
  for (const [sub, target] of entries) {
    if (isUi && sub.startsWith("./components/")) continue
    if (sub.endsWith(".css")) {
      lines.push(`| \`${pkg.name}${sub.slice(1)}\` | — | stylesheet |`)
      continue
    }
    // Read the SOURCE, not the built output: dist has comments stripped, so a
    // summary generated from it would be empty.
    const built = targetPath(target)
    const source = built.replace("./dist/", "./src/").replace(/\.js$/, ".ts")
    const { symbols, summary } = describe(join(ROOT, "packages", pkgDir, source)).symbols.length
      ? describe(join(ROOT, "packages", pkgDir, source))
      : describe(join(ROOT, "packages", pkgDir, source.replace(/\.ts$/, ".tsx")))
    const path = sub === "." ? pkg.name : `${pkg.name}${sub.slice(1)}`
    const shown = symbols.slice(0, 6).join(", ") + (symbols.length > 6 ? ", …" : "")
    lines.push(`| \`${path}\` | ${shown || "—"} | ${summary.replace(/\|/g, "\\|")} |`)
  }
  lines.push("")
}

lines.push(
  "## Not here",
  "",
  "`scheduled.ts` (app-a cron map — product-specific) · `@dapplelight/signet-blocks` (invite",
  "blocks, deliberately not built) · a UI `form.tsx` (use `@dapplelight/signet-lib/form`).",
  "",
)

writeFileSync(join(ROOT, "API.md"), lines.join("\n"))
console.log(`API.md: ${lines.length} lines`)
