/**
 * One page per package, generated from its package.json and its rows in
 * API.md: an install command and a card per module. Not the README: READMEs
 * are written for maintainers and agents, docs pages stay short and visual.
 * Output is gitignored. Fails if a package has no page.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dirname, "../../..")
const out = join(import.meta.dirname, "../content/docs/packages")

/** Nav groups and labels, in the order a new app touches them. */
const GROUPS: [string, [string, string][]][] = [
  ["Start", [["create-signet-app", "Create Signet App"], ["cli", "CLI"], ["mcp", "MCP Server"]]],
  ["Frontend", [["ui", "UI"], ["tokens", "Tokens"], ["lib", "Client Lib"]]],
  ["Backend", [["server", "Server"], ["db", "Database"], ["payments", "Payments"], ["ai", "AI"]]],
  ["Tooling", [["config", "Config"], ["test", "Test"]]],
]
const LABEL = Object.fromEntries(GROUPS.flatMap(([, items]) => items))
const PACKAGES = Object.keys(LABEL)

const found = readdirSync(join(root, "packages")).filter((p) =>
  existsSync(join(root, "packages", p, "package.json")),
)
const missing = found.filter((p) => !PACKAGES.includes(p))
if (missing.length) throw new Error(`packages without a docs page: ${missing.join(", ")}`)

/** `| \`@dapplelight/signet-lib/api\` | exports | What |` rows, per package. */
function modules(name: string) {
  const api = readFileSync(join(root, "API.md"), "utf8")
  const section = api.split(/^## /m).find((s) => s.startsWith(`${name}\n`))
  if (!section) return []
  return [...section.matchAll(/^\| `([^`]+)` \| ([^|]*) \| (.*) \|$/gm)].map(
    ([, path, exports, what]) => ({
      path,
      title: path === name ? "main" : path.slice(name.length + 1),
      // "re-exports a, b, c" says nothing; show the first exports instead.
      what: what.startsWith("re-exports")
        ? exports
            .split(", ")
            .filter((e) => e !== "…")
            .slice(0, 4)
            .join(", ")
        : short(what),
    }),
  )
}

/** First clause, at most ~10 words: a card caption, not a paragraph. */
function short(text: string) {
  const clause = text
    .replace(/`/g, "")
    .replace(/\s*\(.*?\)/g, "")
    .split(/[:;.]\s|, plus | — /)[0]
  const words = clause.split(/\s+/)
  return words.length > 10 ? `${words.slice(0, 10).join(" ")}…` : clause
}

const esc = (s: string) => s.replace(/"/g, "&quot;").replace(/[{}<>]/g, "")

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
for (const pkg of PACKAGES) {
  const m = JSON.parse(readFileSync(join(root, "packages", pkg, "package.json"), "utf8"))
  const cli = m.bin && !m.exports
  const install = cli ? `npx ${m.name}` : `npm i ${m.name}`
  const mods = modules(m.name)
  const cards = mods.length
    ? `## Modules\n\n<Cards>\n${mods
        .map((x) => `  <Card title="${esc(x.title)}" description="${esc(x.what)}" />`)
        .join("\n")}\n</Cards>\n`
    : ""
  writeFileSync(
    join(out, `${pkg}.mdx`),
    `---\ntitle: "${LABEL[pkg]}"\ndescription: "${esc(m.description ?? "")}"\n---\n\n` +
      `\`\`\`bash\n${install}\n\`\`\`\n\n${cards}`,
  )
}
writeFileSync(
  join(out, "meta.json"),
  `${JSON.stringify({ title: "Packages", root: true, pages: GROUPS.flatMap(([g, items]) => [`---${g}---`, ...items.map(([p]) => p)]) }, null, 2)}\n`,
)
console.log(`docs: ${PACKAGES.length} package pages`)

// ------------------------------------------------------------ components
// One page per component from the MCP index (packages/mcp/src/generated).
// A component with a real example gets a live preview; the demos live in
// one client module behind an error boundary, so a demo that needs state
// shows its code instead of breaking the build. Hand-written pages
// (button.mdx) win over generated ones.
const compDir = join(import.meta.dirname, "../content/docs/components")
const { INDEX } = await import("../../../packages/mcp/src/generated/index.ts")
type Comp = {
  name: string
  importPath: string
  exports: string[]
  props: Record<string, string>
  cva: { variants: Record<string, string[]>; defaults: Record<string, string> }[]
  example: string
  summary: string
}
const comps = (INDEX.components as Comp[]).filter((c) => c.importPath.includes("signet-ui"))
const kind = (c: Comp) =>
  c.importPath.includes("/domain/")
    ? "domain"
    : c.importPath.includes("/screens/")
      ? "screens"
      : "ui"
// Generated pages start with this marker; anything else is hand-written
// (and listed as a !exception in .gitignore).
const MARK = "{/* generated by scripts/sync.ts */}"
for (const f of readdirSync(compDir))
  if (f.endsWith(".mdx") && readFileSync(join(compDir, f), "utf8").includes(MARK))
    rmSync(join(compDir, f))
const handWritten = new Set(
  readdirSync(compDir)
    .filter((f) => f.endsWith(".mdx"))
    .map((f) => f.replace(".mdx", "")),
)

const titleOf = (n: string) =>
  n
    .split("-")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(" ")
const bodyOf = (c: Comp) =>
  c.example
    .split("\n")
    .filter((l) => !l.startsWith("import "))
    .join("\n")
    .trim()
// Some index examples are stubs ("<Combobox />" after a signature comment)
// or cut off; only a parseable JSX example gets a live preview.
const tsx = new Bun.Transpiler({ loader: "tsx" })
const parses = (src: string) => {
  try {
    tsx.transformSync(`const x = (<>\n${src}\n</>)`)
    return true
  } catch {
    return false
  }
}
const liveSet = new Set(
  comps.filter((c) => bodyOf(c).startsWith("<") && parses(bodyOf(c))).map((c) => c.name),
)
const live = (c: Comp) => liveSet.has(c.name)
const id = (s: string) => s.replace(/[^a-zA-Z0-9]/g, "_")

// The demos module: namespace imports, one function per demo.
const mods = new Set<string>()
const fns: string[] = []
for (const c of comps.filter(live)) {
  const names: string[] = []
  for (const m of c.example.matchAll(/^import \{([^}]+)\} from "([^"]+)"/gm)) {
    mods.add(m[2])
    names.push(`const {${m[1]}} = ${id(m[2])}`)
  }
  fns.push(
    `  "${c.name}": () => {\n    ${names.join("\n    ")}\n    return (<>\n${bodyOf(c)}\n</>)\n  },`,
  )
}
writeFileSync(
  join(import.meta.dirname, "../components/demos.generated.tsx"),
  `// @ts-nocheck generated by scripts/sync.ts from the MCP index examples\n"use client"\n${[
    ...mods,
  ]
    .map((m) => `import * as ${id(m)} from "${m}"`)
    .join(
      "\n",
    )}\n\nexport const DEMOS: Record<string, () => React.ReactNode> = {\n${fns.join("\n")}\n}\n`,
)

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ")
for (const c of comps) {
  if (handWritten.has(c.name)) continue
  const fence = `\`\`\`tsx\n${c.example}\n\`\`\``
  const preview = live(c)
    ? `<Preview>\n  <Demo name="${c.name}" />\n\n${fence}\n\n</Preview>\n`
    : ""
  const variants = c.cva.flatMap((v) =>
    Object.entries(v.variants).map(
      ([k, vals]) =>
        `| \`${k}\` | ${vals.map((x) => `\`${x}\``).join(" ")} | \`${v.defaults[k] ?? "—"}\` |`,
    ),
  )
  const api = [
    "## API Reference",
    "",
    ...(variants.length
      ? ["| Prop | Values | Default |", "| --- | --- | --- |", ...variants, ""]
      : []),
    "| Export | Props |",
    "| --- | --- |",
    ...c.exports.map((e) => `| \`${e}\` | ${c.props[e] ? `\`${cell(c.props[e])}\`` : "—"} |`),
  ].join("\n")
  const description = esc(c.summary || `${titleOf(c.name)} from signet-ui.`)
  writeFileSync(
    join(compDir, `${c.name}.mdx`),
    `---\ntitle: "${titleOf(c.name)}"\ndescription: "${description}"\n---\n\n${MARK}\n\n${preview}\n` +
      `## Installation\n\n\`\`\`bash\nnpm i @dapplelight/signet-ui\n\`\`\`\n\n` +
      `## Usage\n\n${live(c) ? `\`\`\`tsx\nimport { ${c.exports.join(", ")} } from "${c.importPath}"\n\`\`\`` : fence}\n\n${api}\n`,
  )
}
const page = (c: Comp) => c.name
const group = (k: string) => comps.filter((c) => kind(c) === k).map(page)
writeFileSync(
  join(compDir, "meta.json"),
  `${JSON.stringify(
    {
      title: "Components",
      root: true,
      pages: [
        "---Components---",
        ...group("ui"),
        "---Domain---",
        ...group("domain"),
        "---Screens---",
        ...group("screens"),
      ],
    },
    null,
    2,
  )}\n`,
)
const missingPages = comps.filter((c) => !existsSync(join(compDir, `${page(c)}.mdx`)))
if (missingPages.length)
  throw new Error(`components without a page: ${missingPages.map((c) => c.name).join(", ")}`)
console.log(
  `docs: ${comps.length} component pages (${comps.filter(live).length} with a live preview)`,
)
