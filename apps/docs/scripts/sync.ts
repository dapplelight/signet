/**
 * Package nav and coverage: every package and every module area it exports
 * (per API.md) must have a hand-written page under content/docs/packages.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dirname, "../../..")
const out = join(import.meta.dirname, "../content/docs/packages")

/** Nav groups and labels, in the order a new app touches them. */
const GROUPS: [string, [string, string][]][] = [
  [
    "Start",
    [
      ["create-signet-app", "Create Signet App"],
      ["cli", "CLI"],
      ["mcp", "MCP Server"],
    ],
  ],
  [
    "Frontend",
    [
      ["ui", "UI"],
      ["tokens", "Tokens"],
      ["lib", "Client Lib"],
    ],
  ],
  [
    "Backend",
    [
      ["server", "Server"],
      ["spec", "Spec"],
      ["db", "Database"],
      ["payments", "Payments"],
      ["ai", "AI"],
    ],
  ],
  [
    "Tooling",
    [
      ["config", "Config"],
      ["test", "Test"],
    ],
  ],
]
const LABEL = Object.fromEntries(GROUPS.flatMap(([, items]) => items))
const PACKAGES = Object.keys(LABEL)

const found = readdirSync(join(root, "packages")).filter((p) =>
  existsSync(join(root, "packages", p, "package.json")),
)
const missing = found.filter((p) => !PACKAGES.includes(p))
if (missing.length) throw new Error(`packages without a docs page: ${missing.join(", ")}`)

/** Stylesheet exports share one "themes" page; `biome.json` is `biome`. */
const area = (a: string) => (a.endsWith(".css") ? "themes" : a.replace(/\.json$/, ""))

/** Module areas a package exports, from API.md: `server/http/cors` -> `http`. */
function areas(name: string) {
  const api = readFileSync(join(root, "API.md"), "utf8")
  const section = api.split(/^## /m).find((s) => s.startsWith(`${name}\n`))
  if (!section) return []
  const paths = [...section.matchAll(/^\| `([^`]+)` \|/gm)].map(([, p]) => p)
  return [
    ...new Set(
      paths.filter((p) => p !== name).map((p) => area(p.slice(name.length + 1).split("/")[0])),
    ),
  ]
}

const esc = (s: string) => s.replace(/"/g, "&quot;").replace(/[{}<>]/g, "")

// Package pages are hand-written: content/docs/packages/<pkg>/index.mdx plus
// one page per module area. This only builds the nav and fails the build if
// a package or an exported area has no page.
const gaps: string[] = []
for (const pkg of PACKAGES) {
  const dir = join(out, pkg)
  const name = JSON.parse(readFileSync(join(root, "packages", pkg, "package.json"), "utf8")).name
  if (!existsSync(join(dir, "index.mdx"))) gaps.push(`${pkg}/index.mdx`)
  const want = areas(name)
  for (const a of want) if (!existsSync(join(dir, `${a}.mdx`))) gaps.push(`${pkg}/${a}.mdx`)
  const extra = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith(".mdx") && f !== "index.mdx")
        .map((f) => f.slice(0, -4))
        .filter((f) => !want.includes(f))
    : []
  mkdirSync(dir, { recursive: true })
  writeFileSync(
    join(dir, "meta.json"),
    `${JSON.stringify({ title: LABEL[pkg], pages: ["index", ...want, ...extra] }, null, 2)}\n`,
  )
}
if (gaps.length && !process.env.DOCS_ALLOW_GAPS)
  throw new Error(`package docs missing (${gaps.length}): ${gaps.join(", ")}`)
writeFileSync(
  join(out, "meta.json"),
  `${JSON.stringify({ title: "Packages", root: true, pages: ["index", ...GROUPS.flatMap(([g, items]) => [`---${g}---`, ...items.map(([p]) => p)])] }, null, 2)}\n`,
)
console.log(`docs: ${PACKAGES.length} package pages`)

// ------------------------------------------------------------ components
// One page per component from the MCP index (packages/mcp/src/generated).
// A component with a real example gets a live preview; the demos live in
// one client module behind an error boundary, so a demo that needs state
// shows its code instead of breaking the build. Hand-written pages
// (button.mdx) win over generated ones.
const compDir = join(import.meta.dirname, "../content/docs/components")
const { INDEX } = await import("../../../packages/mcp/src/generated/index.ts")
type Comp = {
  name: string
  importPath: string
  exports: string[]
  props: Record<string, string>
  cva: { variants: Record<string, string[]>; defaults: Record<string, string> }[]
  example: string
  summary: string
}
const comps = (INDEX.components as Comp[]).filter((c) => c.importPath.includes("signet-ui"))
const kind = (c: Comp) =>
  c.importPath.includes("/domain/")
    ? "domain"
    : c.importPath.includes("/screens/")
      ? "screens"
      : "ui"
// Generated pages start with this marker; anything else is hand-written
// (and listed as a !exception in .gitignore).
const MARK = "{/* generated by scripts/sync.ts */}"
for (const f of readdirSync(compDir))
  if (f.endsWith(".mdx") && readFileSync(join(compDir, f), "utf8").includes(MARK))
    rmSync(join(compDir, f))
const handWritten = new Set(
  readdirSync(compDir)
    .filter((f) => f.endsWith(".mdx"))
    .map((f) => f.replace(".mdx", "")),
)

const titleOf = (n: string) =>
  n
    .split("-")
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(" ")
const bodyOf = (c: Comp) =>
  c.example
    .split("\n")
    .filter((l) => !l.startsWith("import "))
    .join("\n")
    .trim()
// Some index examples are stubs ("<Combobox />" after a signature comment)
// or cut off; only a parseable JSX example gets a live preview.
const tsx = new Bun.Transpiler({ loader: "tsx" })
const parses = (src: string) => {
  try {
    tsx.transformSync(`const x = (<>\n${src}\n</>)`)
    return true
  } catch {
    return false
  }
}
const liveSet = new Set(
  comps.filter((c) => bodyOf(c).startsWith("<") && parses(bodyOf(c))).map((c) => c.name),
)
const live = (c: Comp) => liveSet.has(c.name)
const id = (s: string) => s.replace(/[^a-zA-Z0-9]/g, "_")

// The demos module: namespace imports, one function per demo.
const mods = new Set<string>()
const fns: string[] = []
for (const c of comps.filter(live)) {
  const names: string[] = []
  for (const m of c.example.matchAll(/^import \{([^}]+)\} from "([^"]+)"/gm)) {
    mods.add(m[2])
    names.push(`const {${m[1]}} = ${id(m[2])}`)
  }
  fns.push(
    `  "${c.name}": () => {\n    ${names.join("\n    ")}\n    return (<>\n${bodyOf(c)}\n</>)\n  },`,
  )
}
writeFileSync(
  join(import.meta.dirname, "../components/demos.generated.tsx"),
  `// @ts-nocheck generated by scripts/sync.ts from the MCP index examples\n"use client"\n${[
    ...mods,
  ]
    .map((m) => `import * as ${id(m)} from "${m}"`)
    .join(
      "\n",
    )}\n\nexport const DEMOS: Record<string, () => React.ReactNode> = {\n${fns.join("\n")}\n}\n`,
)

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ")
for (const c of comps) {
  if (handWritten.has(c.name)) continue
  const fence = `\`\`\`tsx\n${c.example}\n\`\`\``
  const preview = live(c)
    ? `<Preview>\n  <Demo name="${c.name}" />\n\n${fence}\n\n</Preview>\n`
    : ""
  const variants = c.cva.flatMap((v) =>
    Object.entries(v.variants).map(
      ([k, vals]) =>
        `| \`${k}\` | ${vals.map((x) => `\`${x}\``).join(" ")} | \`${v.defaults[k] ?? "—"}\` |`,
    ),
  )
  const api = [
    "## API Reference",
    "",
    ...(variants.length
      ? ["| Prop | Values | Default |", "| --- | --- | --- |", ...variants, ""]
      : []),
    "| Export | Props |",
    "| --- | --- |",
    ...c.exports.map((e) => `| \`${e}\` | ${c.props[e] ? `\`${cell(c.props[e])}\`` : "—"} |`),
  ].join("\n")
  const description = esc(c.summary || `${titleOf(c.name)} from signet-ui.`)
  writeFileSync(
    join(compDir, `${c.name}.mdx`),
    `---\ntitle: "${titleOf(c.name)}"\ndescription: "${description}"\n---\n\n${MARK}\n\n${preview}\n` +
      `## Installation\n\n\`\`\`bash\nnpm i @dapplelight/signet-ui\n\`\`\`\n\n` +
      `## Usage\n\n${live(c) ? `\`\`\`tsx\nimport { ${c.exports.join(", ")} } from "${c.importPath}"\n\`\`\`` : fence}\n\n${api}\n`,
  )
}
const page = (c: Comp) => c.name
const group = (k: string) => comps.filter((c) => kind(c) === k).map(page)
writeFileSync(
  join(compDir, "meta.json"),
  `${JSON.stringify(
    {
      title: "Components",
      root: true,
      pages: [
        "index",
        "---Primitives---",
        ...group("ui"),
        "---Domain---",
        ...group("domain"),
        "---Screens---",
        ...group("screens"),
      ],
    },
    null,
    2,
  )}\n`,
)
const missingPages = comps.filter((c) => !existsSync(join(compDir, `${page(c)}.mdx`)))
if (missingPages.length)
  throw new Error(`components without a page: ${missingPages.map((c) => c.name).join(", ")}`)

// The /docs/components grid: one card per page, title and description from
// its frontmatter, alphabetical. Generated so a new component is never missing.
const front = (src: string, key: string) => new RegExp(`^${key}: "(.*)"$`, "m").exec(src)?.[1] ?? ""
const cards = comps
  .map((c) => {
    const src = readFileSync(join(compDir, `${page(c)}.mdx`), "utf8")
    const description = front(src, "description")
    return {
      href: `/docs/components/${page(c)}`,
      title: front(src, "title"),
      description: kind(c) === "domain" ? `Domain: ${description}` : description,
    }
  })
  .sort((a, b) => a.title.localeCompare(b.title))
writeFileSync(
  join(compDir, "index.mdx"),
  `---\ntitle: "Components"\ndescription: "Themed, accessible React components, domain blocks and screens from signet-ui."\n---\n\n${MARK}\n\n<Cards>\n${cards
    .map(
      (c) =>
        `  <Card title="${esc(c.title)}" href="${c.href}" description="${esc(c.description)}" />`,
    )
    .join("\n")}\n</Cards>\n`,
)
console.log(
  `docs: ${comps.length} component pages (${comps.filter(live).length} with a live preview)`,
)

/**
 * Home-page theme switcher: each shipped theme's tokens scoped to
 * [data-signet-theme="<name>"], read from the real theme files. Editorial is
 * the site's own theme, so its scope adds nothing and the page tokens apply.
 */
const themeDir = join(root, "packages/tokens/src/themes")
const block = (css: string, at: string) =>
  css.match(new RegExp(`${at} \\{([\\s\\S]*?)\\n\\}`))?.[1] ?? ""
function scopedTheme(name: string) {
  const css = readFileSync(join(themeDir, `${name}.css`), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")
  const sel = `[data-signet-theme="${name}"]`
  const rules = [...block(css, "@layer base").matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(
    ([, selector, body]) => `${selector.includes(".dark") ? `.dark ${sel}` : sel} {${body}}`,
  )
  // Geometry and type from @theme; global.css makes the utilities read these as vars.
  const geometry = block(css, "@theme inline")
    .split(";")
    .map((d) => d.trim())
    .filter((d) => /^--(text|radius|spacing|font-weight)[\w-]*:/.test(d))
  if (geometry.length) rules.push(`${sel} {\n  ${geometry.join(";\n  ")};\n}`)
  return rules.join("\n")
}
writeFileSync(
  join(import.meta.dirname, "../app/themes.generated.css"),
  `/* Generated by scripts/sync.ts from packages/tokens/src/themes. */\n${["cinematic"].map(scopedTheme).join("\n")}\n`,
)
